/**
 * UIScene lifecycle config plugin (INT-620).
 *
 * Apps linked against the iOS 27 SDK must adopt the UIScene lifecycle. A build
 * that still creates its window in `application(_:didFinishLaunchingWithOptions:)`
 * is stopped by UIKit at launch with EXC_BREAKPOINT in
 * `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`. This was
 * measured on 18 Nov 2026: a Release simulator build from Xcode 27.2 / iOS 27.2
 * crashed on launch before this plugin, and opened the welcome screen after it
 * (docs/evidence/INT-620.md).
 *
 * The plugin does three things:
 * 1. Writes `SceneDelegate.swift` into the app target. It creates the window from
 *    the `UIWindowScene` and starts React Native in it through the factory the
 *    AppDelegate already holds, and it forwards opened URLs and user activities
 *    to `RCTLinkingManager`, as the AppDelegate did.
 * 2. Removes the window creation from the generated `AppDelegate.swift`, so React
 *    Native starts exactly once. If the expected block is not found, the plugin
 *    throws: a silent no-op would ship a build that crashes or starts twice.
 * 3. Declares `UIApplicationSceneManifest` with one scene configuration that
 *    names the delegate, and `UIApplicationSupportsMultipleScenes` false.
 */
const fs = require("fs");
const path = require("path");
const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require("expo/config-plugins");

const SCENE_DELEGATE_FILE = "SceneDelegate.swift";

const SCENE_DELEGATE_SWIFT = `import UIKit
import React

// Generated by plugins/withSceneLifecycle.js (INT-620). Do not edit by hand.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate,
          let factory = appDelegate.reactNativeFactory else { return }
    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: nil)
    for context in connectionOptions.urlContexts {
      _ = RCTLinkingManager.application(UIApplication.shared, open: context.url, options: [:])
    }
    for activity in connectionOptions.userActivities {
      _ = RCTLinkingManager.application(UIApplication.shared, continue: activity, restorationHandler: { _ in })
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    for context in URLContexts {
      _ = RCTLinkingManager.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = RCTLinkingManager.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

const WINDOW_BLOCK =
  /#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\(\n\s*withModuleName: "main",\n\s*in: window,\n\s*launchOptions: launchOptions\)\n#endif\n/;

const MARKER = "// INT-620: the window is created by SceneDelegate (UIScene lifecycle).";

/** Remove the AppDelegate's own window creation. Throws if it is not found. */
function patchAppDelegate(contents) {
  if (contents.includes(MARKER)) return contents;
  if (!WINDOW_BLOCK.test(contents)) {
    throw new Error(
      "withSceneLifecycle: the AppDelegate window block was not found; " +
        "update the plugin for this Expo template before building (INT-620).",
    );
  }
  return contents.replace(WINDOW_BLOCK, `    ${MARKER}\n`);
}

/** The scene manifest every build declares. */
function sceneManifest() {
  return {
    UIApplicationSupportsMultipleScenes: false,
    UISceneConfigurations: {
      UIWindowSceneSessionRoleApplication: [
        {
          UISceneConfigurationName: "Default Configuration",
          UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
        },
      ],
    },
  };
}

function withSceneLifecycle(config) {
  config = withAppDelegate(config, (mod) => {
    if (mod.modResults.language !== "swift") {
      throw new Error("withSceneLifecycle: only the Swift AppDelegate is supported (INT-620).");
    }
    mod.modResults.contents = patchAppDelegate(mod.modResults.contents);
    return mod;
  });
  config = withInfoPlist(config, (mod) => {
    mod.modResults.UIApplicationSceneManifest = sceneManifest();
    return mod;
  });
  config = withDangerousMod(config, [
    "ios",
    (mod) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
      const target = path.join(
        mod.modRequest.platformProjectRoot,
        projectName,
        SCENE_DELEGATE_FILE,
      );
      fs.writeFileSync(target, SCENE_DELEGATE_SWIFT);
      return mod;
    },
  ]);
  config = withXcodeProject(config, (mod) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
    const filepath = `${projectName}/${SCENE_DELEGATE_FILE}`;
    if (!mod.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: mod.modResults,
      });
    }
    return mod;
  });
  return config;
}

module.exports = withSceneLifecycle;
module.exports.patchAppDelegate = patchAppDelegate;
module.exports.sceneManifest = sceneManifest;
module.exports.SCENE_DELEGATE_SWIFT = SCENE_DELEGATE_SWIFT;
