#!/usr/bin/env python3
"""Physician sign-off packets, one per department (INT-388).

Renders docs/signoff/<packet>.md for every committed review candidate (the clusters
and the specialty branches) from the candidate, its proposal and the verification
trail, with no hand-copied text (scripts/dev/signoff_content.py, signoff_trail.py):

1. the questions in the resolved ask order, Turkish text verbatim from the candidate;
2. the proposal's §1 sources; 3. the candidate's red-flag stubs;
4. every open item of the verification trail that names the packet;
5. a signature block recording a decision per open item. Signing never edits a pack.

Also docs/signoff/README.md (how to sign, how decisions flow back, counts) and
docs/signoff/_unassigned.md (open items that name no packet; the drift test in
tests/protocols/test_signoff_packet.py requires it to list none).

    uv run python scripts/dev/signoff_packet.py          # write docs/signoff/
    uv run python scripts/dev/signoff_packet.py --check  # exit 1 on drift
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Sequence
from itertools import zip_longest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from signoff_content import (  # noqa: E402
    DASH,
    GENERATOR,
    ROOT,
    TENSE_ANCHOR_TYPE,
    Packet,
    cell,
    code,
    excluded_items,
    git_blob,
    guard,
    packets,
    question_rows,
    red_flags,
    rel,
    sha256,
    sources,
    taxonomy,
)
from signoff_trail import (  # noqa: E402
    Item,
    NameIndex,
    assign,
    open_items,
    trail_documents,
)

OUT = ROOT / "docs/signoff"
README = "README.md"
UNASSIGNED = "_unassigned.md"
SCRIPT = "scripts/dev/signoff_packet.py"
NOTICE = (
    f"Generated by `{SCRIPT}` from the committed candidates, proposals and verification "
    "trail. Regenerate it; never edit it by hand. A packet records decisions and never "
    "edits a pack."
)
INT383 = (
    "INT-383 (GitHub #630): this stub's `tense_anchor` names a `{kind}` slot. The engine "
    "reads only ISO dates for a tense anchor, so the anchor can never fire. The clinician "
    "chooses the anchor when the stub is sourced and signed (HB-C1)."
)
Filed = dict[tuple[str, int], list[str]]


def _count(n: int, noun: str) -> str:
    return f"{n} {noun}" + ("" if n == 1 else "s")


def _decider_key(tag: str) -> tuple[int, str, int]:
    hb = re.match(r"HB-([A-Z]+)(\d+)", tag)
    return (0, hb.group(1), int(hb.group(2))) if hb else (1, tag, 0)


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    return [
        "| " + " | ".join(header) + " |",
        "|" + "---|" * len(header),
        *("| " + " | ".join(row) + " |" for row in rows),
    ]


def _header(p: Packet) -> list[str]:
    doc = p.doc
    steps = ["`base.intake`", f"`cluster.{p.cluster}`"]
    steps += [f"`{doc['id']}`"] if p.kind == "branch" else []
    ops = ", ".join(f"`{op['op']}` `{op.get('pointer', '')}`" for op in doc.get("ops") or [])
    generator = (
        f"`{rel(GENERATOR)}` at git blob `{git_blob(GENERATOR)}`"
        if p.generated
        else "none: a hand-authored candidate (no generator marker)"
    )
    rows = [("packet", f"`{p.key}`")]
    if p.kind == "branch":
        rows += [
            ("branch", f"`{p.key}` · {cell(p.title)}"),
            ("cluster", f"`cluster.{p.cluster}` (packet `cluster_{p.cluster}.md`)"),
        ]
    else:
        members = sorted(b["id"] for b in taxonomy()["branches"] if b["cluster"] == p.cluster)
        rows += [
            ("cluster", f"`cluster.{p.cluster}` · {cell(p.title)}"),
            ("member branches", ", ".join(f"`{m}`" for m in members) or DASH),
        ]
    rows += [
        ("candidate", f"`{rel(p.candidate)}`"),
        ("candidate sha256", f"`{sha256(p.candidate)}`"),
        ("candidate status", cell(f"{doc.get('maturity')} · {doc.get('status')}")),
        ("proposal", f"`{rel(p.proposal)}`"),
        ("generator", generator),
        ("chain", " → ".join(steps) + (f" (ops: {ops})" if ops else "")),
    ]
    return _table(("field", "value"), rows)


def _questions(p: Packet) -> list[str]:
    rows = question_rows(p)
    out = [
        "## 1. Questions in the resolved ask order",
        "",
        "The chain is merged by the resolver (`_merge_chain`, then `_apply_ops`) and read "
        "in the engine's order: must-ask before detail, then merged position. `#` is the "
        "place among the chain's pack questions; a missing number is a "
        f"`cluster.{p.cluster}` question this candidate inherits. `Q` is the proposal's "
        f"question number. Text is the candidate's, verbatim; — marks a field the candidate "
        f"does not set. {_count(len(rows), 'question')}.",
        "",
        *_table(
            ("#", "Q", "slot", "type", "ask (tr)", "follow-up (tr)", "gate", "delivery", "layer"),
            [
                (
                    str(r.position),
                    str(r.number) if r.number is not None else DASH,
                    f"`{r.section}.{r.slot}`",
                    r.type,
                    cell(r.ask) if r.ask else DASH,
                    cell(r.follow_up) if r.follow_up else DASH,
                    code(r.gate),
                    r.delivery or DASH,
                    r.layer,
                )
                for r in rows
            ],
        ),
        "",
        "### Proposal items not in the candidate",
        "",
    ]
    held = excluded_items(p)
    if not p.generated:
        out.append("A hand-authored candidate: the generator does not map its proposal.")
    elif not held:
        out.append("None: every proposal item is in the candidate.")
    else:
        out += _table(
            ("Q", "slot", "ask (tr)", "generator note"),
            [(q, code(slot), cell(text), cell(note)) for q, slot, text, note in held],
        )
    return out


def _sources(p: Packet) -> list[str]:
    found = sources(p)
    out = [
        "## 2. Sources (proposal §1)",
        "",
        f"{_count(len(found), 'source')}, as the proposal states them; — where it states none.",
    ]
    if found:
        out += [
            "",
            *_table(
                ("#", "source", "guideline id", "version / date", "URL", "retrieved_on"),
                [
                    (
                        str(n),
                        cell(s.heading),
                        cell(s.guideline_id) if s.guideline_id else DASH,
                        cell(s.version) if s.version else DASH,
                        "<br>".join(cell(u) for u in s.urls) or DASH,
                        cell(s.retrieved_on) if s.retrieved_on else DASH,
                    )
                    for n, s in enumerate(found, 1)
                ],
            ),
        ]
    return out


def _stubs(p: Packet) -> list[str]:
    stubs = red_flags(p)
    out = ["## 3. Red-flag stubs", "", f"{_count(len(stubs), 'rule')} in the candidate, verbatim."]
    for rule, anchor_type in stubs:
        anchor = rule.get("tense_anchor")
        fields = [("status", code(rule.get("status")))]
        fields.append(("tense_anchor", f"{code(anchor)} ({anchor_type or 'not in the chain'})"))
        keys = ("tense", "level", "route", "notify_clinic", "label_tr", "when", "source_gap")
        fields += [(k, cell(rule[k])) for k in keys if k in rule]
        out += ["", f"### `{rule.get('id')}`", "", *_table(("field", "value"), fields)]
        if anchor and anchor_type != TENSE_ANCHOR_TYPE:
            out += ["", f"> {INT383.format(kind=anchor_type or 'undeclared')}"]
    return out


def _item(n: int, item: Item, others: Sequence[str]) -> list[str]:
    labels = [h or f"column {i}" for i, h in enumerate(item.header, 1)]
    return [
        f"### OI-{n} · {item.ref}",
        "",
        f"- section: {guard(item.heading)}",
        f"- deciders: {', '.join(item.deciders)}",
        f"- also filed under: {', '.join(f'`{k}`' for k in others) or DASH}",
        "- row, as recorded:",
        *(
            f"  - **{guard(h)}**: {guard(c)}"
            for h, c in zip_longest(labels, item.cells, fillvalue="")
        ),
        "",
    ]


def _items(p: Packet, items: Sequence[Item], filed_in: Filed) -> list[str]:
    out = ["## 4. Open items", "", f"{_count(len(items), 'open item')} naming this packet.", ""]
    for n, item in enumerate(items, 1):
        others = [k for k in filed_in[(item.doc, item.line)] if k != p.key]
        out += _item(n, item, others)
    return out


def _signature(p: Packet, items: Sequence[Item]) -> list[str]:
    decisions = [(f"OI-{n} · {item.ref}", " ") for n, item in enumerate(items, 1)]
    return [
        "## 5. Signature",
        "",
        "Fill this block on a copy under `docs/signoff/signed/` (README.md, How to sign).",
        "",
        *_table(
            ("field", "entry"),
            [
                ("signer", " "),
                ("role", " "),
                ("date", " "),
                ("candidate sha256", f"`{sha256(p.candidate)}`"),
            ],
        ),
        "",
        *_table(
            ("item", "decision: accept / change: <text> / reject"), decisions or [(DASH, DASH)]
        ),
    ]


def render_packet(p: Packet, items: Sequence[Item], filed_in: Filed) -> str:
    parts = [
        [f"# Sign-off packet: {p.title} (`{p.key}`)", "", NOTICE, ""],
        _header(p),
        [""],
        _questions(p),
        [""],
        _sources(p),
        [""],
        _stubs(p),
        [""],
        _items(p, items, filed_in),
        _signature(p, items),
    ]
    return "\n".join(line for part in parts for line in part).rstrip() + "\n"


def render_unassigned(unassigned: Sequence[Item]) -> str:
    lines = [
        "# Open items that name no packet",
        "",
        NOTICE,
        "",
        f"{_count(len(unassigned), 'open item')}. Each names no branch or cluster by slug, Turkish "
        "name, name prefix or slot id. None is forced into a packet: the drift test "
        "requires this list to be empty, so each one waits for a human to route it.",
        "",
    ]
    for n, item in enumerate(unassigned, 1):
        lines += _item(n, item, [])
    return "\n".join(lines).rstrip() + "\n"


def render_readme(
    all_packets: Sequence[Packet],
    items: Sequence[Item],
    filed: dict[str, list[Item]],
    unassigned: Sequence[Item],
) -> str:
    kinds = [p.kind for p in all_packets]
    deciders = sorted({d for i in items for d in i.deciders}, key=_decider_key)
    by_decider = [
        (
            f"`{d}`" if d.startswith("HB-") else d,
            str(sum(d in i.deciders for i in items)),
            str(sum(any(d in i.deciders for i in its) for its in filed.values())),
            str(sum(d in i.deciders for i in unassigned)),
        )
        for d in deciders
    ]
    per_packet = [
        (
            f"[`{p.key}`]({p.key}.md)",
            cell(p.title),
            f"`{p.cluster}`",
            str(len(question_rows(p))),
            str(len(sources(p))),
            str(len(red_flags(p))),
            str(len(filed.get(p.key, []))),
        )
        for p in all_packets
    ]
    docs = ", ".join(f"`{rel(d)}`" for d in trail_documents())
    lines = [
        "# Physician sign-off packets",
        "",
        NOTICE,
        "",
        f"One packet per committed review candidate: {kinds.count('cluster')} cluster "
        f"packets and {kinds.count('branch')} branch packets. The verification trail holds "
        f"{len(items)} open items, filed {sum(len(v) for v in filed.values())} times across "
        f"{len(filed)} packets; {len(unassigned)} name no packet ([`{UNASSIGNED}`]({UNASSIGNED})).",
        "",
        "## How to sign",
        "",
        "1. Open the department's packet: `<branch>.md`, or `cluster_<id>.md` for the "
        "questions every member branch inherits. Read §1 to §3, then each open item in §4.",
        "2. Copy the packet to `docs/signoff/signed/<packet>-<YYYY-MM-DD>.md`. The generator "
        "writes only the top level of `docs/signoff/`, so it never overwrites a signed copy.",
        "3. In the copy's §5, fill signer, role and date, and write one decision per open "
        "item: `accept`, `change: <text>` or `reject`.",
        "4. The candidate sha256 in the header binds the decisions to those candidate bytes. "
        "When the candidate changes, its packet regenerates with a new sha256, and a signed "
        "copy naming the old one no longer describes the candidate.",
        "5. Signing edits no pack. Promotion past L0 still needs the candidate's "
        "`clinical_signoff` block (HB-C1).",
        "",
        "## How decisions flow back",
        "",
        "1. A follow-up PR applies each decision to the proposal "
        "(`docs/evidence/proposals/<slug>.md`), never to a candidate or the served tree.",
        "2. It regenerates the candidates: `uv run python scripts/dev/gen_specialty_packs.py`.",
        "3. An independent verifier checks the regenerated candidates against the decisions "
        "and records the review under `docs/evidence/verification/`.",
        f"4. `uv run python {SCRIPT}` regenerates these packets; `--check` exits 1 on drift, "
        "and `tests/protocols/test_signoff_packet.py` fails on it.",
        "",
        "## How open items are chosen and filed",
        "",
        "- An open item is a table row, outside code fences, that names a human decider "
        "(an HB-C id, a psychiatrist, a paediatrician, the owner, the clinician, or "
        f"`awaiting-human`). The trail read: {docs}.",
        "- A row is filed under every packet that it or its section heading names: by slug, "
        "Turkish name, a prefix of either, the name's initials, or the cluster id "
        "(`scripts/dev/signoff_trail.py`). A row that names no packet is filed under the "
        "packets whose candidates declare a slot id it quotes. A row that names nothing is "
        "listed in `_unassigned.md` and is never forced into a packet.",
        "- Deciders are the HB ids a row cites, then the roles it names.",
        "",
        "## Open items by decider",
        "",
        *_table(("decider", "open items", "packets", "unassigned"), by_decider),
        "",
        "## Packets",
        "",
        *_table(
            ("packet", "title", "cluster", "questions", "sources", "red-flag stubs", "open items"),
            per_packet,
        ),
    ]
    return "\n".join(lines).rstrip() + "\n"


def render_all() -> dict[str, str]:
    """File name under docs/signoff → content: every packet, the README, the unassigned."""
    all_packets = packets()
    items = open_items(trail_documents())
    filed, unassigned = assign(items, NameIndex(all_packets))
    filed_in: Filed = {}
    for key, its in sorted(filed.items()):
        for item in its:
            filed_in.setdefault((item.doc, item.line), []).append(key)
    out = {f"{p.key}.md": render_packet(p, filed.get(p.key, []), filed_in) for p in all_packets}
    out[UNASSIGNED] = render_unassigned(unassigned)
    out[README] = render_readme(all_packets, items, filed, unassigned)
    return out


def drift(rendered: dict[str, str], out: Path = OUT) -> list[str]:
    """Top-level docs/signoff files that differ from, or are missing in, the rendering."""
    on_disk = {p.name for p in out.glob("*.md")}
    return sorted(
        name
        for name in set(rendered) | on_disk
        if name not in on_disk or (out / name).read_text(encoding="utf-8") != rendered.get(name)
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n", 1)[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/signoff/ drifts")
    args = ap.parse_args(argv)
    rendered = render_all()
    if args.check:
        stale = drift(rendered)
        for name in stale:
            print(f"DRIFT docs/signoff/{name}")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for extra in {p.name for p in OUT.glob("*.md")} - set(rendered):
        (OUT / extra).unlink()
    for name, text in sorted(rendered.items()):
        (OUT / name).write_text(text, encoding="utf-8")
    print(f"wrote {len(rendered)} files to docs/signoff/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
