"""Emit or check the staff Grafana's operations dashboards (INT-481).

The dashboards are generated by :mod:`intake_platform.ops_dashboards` from the
SLO files under docs/slo, and committed under
infra/observability/grafana/ops-dashboards/. tests/observability/
test_ops_dashboards.py fails when the committed JSON differs from what this
script would write.

Usage:
    uv run python scripts/observability/ops_dashboards.py --check
    uv run python scripts/observability/ops_dashboards.py --emit
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from intake_platform.ops_dashboards import (
    DASHBOARD_DIR,
    dashboard_filename,
    ops_dashboards,
    render_dashboard,
)
from intake_platform.slo import load_slo_file

REPO = Path(__file__).resolve().parents[2]


def rendered() -> dict[Path, str]:
    slo_files = [load_slo_file(path) for path in sorted((REPO / "docs" / "slo").glob("*.yaml"))]
    return {
        REPO / DASHBOARD_DIR / dashboard_filename(slug): render_dashboard(dashboard)
        for slug, dashboard in ops_dashboards(slo_files).items()
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--emit", action="store_true", help="write every dashboard")
    mode.add_argument("--check", action="store_true", help="fail on any drift")
    args = parser.parse_args(argv)
    expected = rendered()
    if args.emit:
        (REPO / DASHBOARD_DIR).mkdir(parents=True, exist_ok=True)
        for path, text in expected.items():
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")
        return 0
    drift = [
        str(path.relative_to(REPO))
        for path, text in expected.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != text
    ]
    stray = sorted(
        str(path.relative_to(REPO))
        for path in (REPO / DASHBOARD_DIR).glob("*.json")
        if path not in expected
    )
    for name in drift:
        print(f"drift: {name}", file=sys.stderr)
    for name in stray:
        print(f"not generated: {name}", file=sys.stderr)
    return 1 if drift or stray else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
