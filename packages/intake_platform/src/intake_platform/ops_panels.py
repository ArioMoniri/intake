"""Panel machinery for the generated operations dashboards (INT-481).

:mod:`intake_platform.ops_dashboards` declares the dashboards; this module turns
a list of :class:`Panel` into Grafana JSON: a 24-column grid filled left to
right, the provisioned Prometheus datasource on every panel, and the deploy
markers on every dashboard. It also holds :func:`slo_budget_expr`, the budget
left over an SLO's own window, which the SLO dashboard draws for every SLO.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import Any

from intake_platform.slo import SLO, error_budget
from intake_platform.slo_dashboards import DATASOURCE, render_dashboard

__all__ = [
    "DASHBOARD_DIR",
    "DEPLOY_MARKER",
    "NO_EMITTER_ON_STAGING",
    "UP_DOWN",
    "Panel",
    "dashboard",
    "dashboard_filename",
    "quantile",
    "render_dashboard",
    "slo_budget_expr",
]

#: Mounted at /etc/grafana/dashboards/ops by infra/staging/compose.obs.yaml.
DASHBOARD_DIR = "infra/observability/grafana/ops-dashboards"
#: The family infra/staging/lib.sh's write_deploy_marker writes as a textfile.
DEPLOY_MARKER = "deploy_event_timestamp_seconds"

_WIDTH = 24
_REF_IDS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
NO_EMITTER_ON_STAGING = (
    " Nothing on the staging host emits this series yet, so there the panel reads "
    "'No data' rather than a figure."
)


@dataclass(frozen=True)
class Panel:
    """One panel: a kind, a title, a unit and its (expression, legend) pairs."""

    kind: str
    title: str
    unit: str
    exprs: tuple[tuple[str, str], ...]
    description: str
    width: int = 12
    height: int = 7
    thresholds: tuple[tuple[str, float | None], ...] = ()
    instant: bool = False
    extra: dict[str, Any] = field(default_factory=dict)


def dashboard_filename(slug: str) -> str:
    return f"{slug}.json"


def slo_budget_expr(slo: SLO) -> str:
    """The share of an SLO's error budget left over its own window.

    The SLI is the error ratio over ``[5m]``; the same ratio over the SLO's
    window is the window's error ratio, and the budget left is one minus that
    ratio over the objective's budget. 1 is untouched, 0 is spent, below 0 is
    overspent.
    """
    ratio = " ".join(slo.sli.split()).replace("[5m]", f"[{slo.window}]")
    return f"1 - (({ratio}) / {error_budget(slo.objective)!r})"


def _targets(panel: Panel) -> list[dict[str, Any]]:
    targets: list[dict[str, Any]] = []
    for index, (expr, legend) in enumerate(panel.exprs):
        target: dict[str, Any] = {"refId": _REF_IDS[index], "expr": expr, "legendFormat": legend}
        if panel.instant:
            target.update({"instant": True, "range": False, "format": "table"})
        targets.append(target)
    return targets


def _layout(panels: Sequence[Panel]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    x = y = row_height = 0
    for index, panel in enumerate(panels, start=1):
        if x + panel.width > _WIDTH:
            x, y, row_height = 0, y + row_height, 0
        defaults: dict[str, Any] = {"unit": panel.unit}
        if panel.thresholds:
            defaults["thresholds"] = {
                "mode": "absolute",
                "steps": [{"color": colour, "value": value} for colour, value in panel.thresholds],
            }
        rendered: dict[str, Any] = {
            "id": index,
            "type": panel.kind,
            "title": panel.title,
            "description": panel.description,
            "datasource": dict(DATASOURCE),
            "gridPos": {"h": panel.height, "w": panel.width, "x": x, "y": y},
            "fieldConfig": {"defaults": defaults, "overrides": []},
            "targets": _targets(panel),
        }
        rendered.update(panel.extra)
        out.append(rendered)
        x += panel.width
        row_height = max(row_height, panel.height)
    return out


def _deploy_annotations() -> dict[str, Any]:
    def marker(stage: str, colour: str) -> dict[str, Any]:
        return {
            "name": f"Deploy {stage}",
            "datasource": dict(DATASOURCE),
            "enable": True,
            "iconColor": colour,
            "expr": f'(time() - {DEPLOY_MARKER}{{stage="{stage}"}}) < 90',
            "step": "30s",
            "titleFormat": f"deploy {stage}",
            "textFormat": "{{head_sha}}",
        }

    return {"list": [marker("started", "orange"), marker("completed", "green")]}


def dashboard(slug: str, title: str, about: str, panels: Sequence[Panel]) -> dict[str, Any]:
    return {
        "__comment": (
            f"{DASHBOARD_DIR}/{dashboard_filename(slug)} — GENERATED by "
            "intake_platform.ops_dashboards (INT-481). Do not edit: change the module and "
            "re-emit with scripts/observability/ops_dashboards.py --emit; "
            "tests/observability/test_ops_dashboards.py fails on drift."
        ),
        "uid": f"intake-ops-{slug}",
        "title": title,
        "description": about,
        "tags": ["ops", "intake", "staging"],
        "timezone": "utc",
        "schemaVersion": 39,
        "version": 1,
        "editable": False,
        "time": {"from": "now-24h", "to": "now"},
        "refresh": "1m",
        "templating": {"list": []},
        "annotations": _deploy_annotations(),
        "panels": _layout(panels),
    }


#: Thresholds for a 1-up, 0-down stat.
UP_DOWN: tuple[tuple[str, float | None], ...] = (("red", None), ("green", 1.0))


def quantile(q: str, family: str, by: str, window: str) -> str:
    """``histogram_quantile`` of a catalogued histogram family, grouped ``by``."""
    return f"histogram_quantile({q}, sum by ({by}) (rate({family}_bucket[{window}])))"
