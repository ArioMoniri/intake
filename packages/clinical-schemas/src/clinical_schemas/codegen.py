"""Deterministic schema exports (INT-031, scope items 2-3).

One generator, three artefacts, all committed and drift-tested:

- ``schemas/openapi.json`` — an OpenAPI 3.1 document whose
  ``components.schemas`` carries every clinical object and event (the
  acceptance's "TS generated from OpenAPI" source of truth);
- ``schemas/events/<name>.v1.json`` — one self-contained JSON Schema per
  versioned event, for stream consumers that validate without OpenAPI;
- ``src/generated/models.ts`` — TypeScript *types only*, emitted by the
  small deterministic generator below (no network, no codegen dependency;
  the pinned toolchain is this package itself).

Determinism contract: byte-identical output for identical model source.
JSON is dumped with sorted keys and a trailing newline; TS is emitted in
sorted schema order. ``tests/schemas/test_roundtrip.py`` regenerates and
compares bytes, so `make check` fails the moment these go stale — rerun
``make schemas-codegen``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter
from pydantic.json_schema import models_json_schema

from clinical_schemas.consent import ConsentScope
from clinical_schemas.events import EVENT_MODELS
from clinical_schemas.note import PatientSummary, PreVisitNote
from clinical_schemas.observers import LaneSignal, ObserverState
from clinical_schemas.previsit_output import PreVisitOutput
from clinical_schemas.overlay import PatientOverlay
from clinical_schemas.proposal import Proposal
from clinical_schemas.records import ExtractedRecordItem
from clinical_schemas.session import SessionState
from clinical_schemas.triage import LlmCandidateTriage, RulesTriageResult, TriageResult

PACKAGE_ROOT = Path(__file__).resolve().parents[2]

OPENAPI_PATH = "schemas/openapi.json"
EVENTS_DIR = "schemas/events"
TS_PATH = "src/generated/models.ts"

# The nine clinical objects of the INT-031 acceptance (TriageResult enters as
# its two discriminated members plus the named union), the recorded lane
# signal (files/03 §4.8), and the six events.
EXPORTED_MODELS: tuple[type[BaseModel], ...] = (
    PreVisitNote,
    # Owner directive: the finished previsit as a hospital receives it. It is
    # exported because the receiver is ANOTHER ORGANISATION's software — the
    # committed OpenAPI document is how "the same structure" is stated to them
    # rather than described in an email.
    PreVisitOutput,
    PatientSummary,
    ExtractedRecordItem,
    ConsentScope,
    RulesTriageResult,
    LlmCandidateTriage,
    SessionState,
    PatientOverlay,
    ObserverState,
    LaneSignal,
    Proposal,
    *EVENT_MODELS.values(),
)

_REF_PREFIX = "#/components/schemas/"


def _component_schemas() -> dict[str, Any]:
    _, defs = models_json_schema(
        [(model, "serialization") for model in EXPORTED_MODELS],
        ref_template=_REF_PREFIX + "{model}",
    )
    schemas: dict[str, Any] = dict(defs.get("$defs", {}))
    union = TypeAdapter(TriageResult).json_schema(
        ref_template=_REF_PREFIX + "{model}", mode="serialization"
    )
    union_defs = union.pop("$defs", {})
    # A PEP 695 alias renders as a $ref into its own $defs — unwrap it so the
    # component carries the union itself.
    if "$ref" in union and _ts_name(union["$ref"]) in union_defs:
        union = union_defs[_ts_name(union["$ref"])]
    schemas["TriageResult"] = union
    return schemas


def _openapi_document() -> dict[str, Any]:
    return {
        "openapi": "3.1.0",
        "info": {
            "title": "INTAKE clinical schemas",
            "version": "0.1.0",
            "description": (
                "Canonical clinical object and event schemas (INT-031). "
                "Generated by clinical_schemas.codegen — regenerate with "
                "`make schemas-codegen`, never edit by hand."
            ),
        },
        "paths": {},
        "components": {"schemas": _component_schemas()},
    }


def _dump_json(document: dict[str, Any]) -> str:
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


# --------------------------------------------------------------------- TS


def _ts_name(ref: str) -> str:
    return ref.removeprefix(_REF_PREFIX)


def _ts_string_literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def _ts_type(schema: dict[str, Any] | bool) -> str:
    """Render one JSON Schema node as a TS type expression."""
    if schema is True or schema == {}:
        return "unknown"
    if schema is False:
        return "never"
    if "$ref" in schema:
        return _ts_name(schema["$ref"])
    if "const" in schema:
        return _ts_string_literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_ts_string_literal(value) for value in schema["enum"])
    for union_key in ("anyOf", "oneOf"):
        if union_key in schema:
            members = [_ts_type(member) for member in schema[union_key]]
            unique: list[str] = []
            for member in members:
                if member not in unique:
                    unique.append(member)
            return " | ".join(unique)
    schema_type = schema.get("type")
    if schema_type == "array":
        if "prefixItems" in schema:
            tuple_members = ", ".join(_ts_type(member) for member in schema["prefixItems"])
            return f"[{tuple_members}]"
        item = _ts_type(schema.get("items", True))
        return f"({item})[]" if " " in item else f"{item}[]"
    if schema_type == "object" or "properties" in schema or "additionalProperties" in schema:
        if "properties" in schema:
            required = set(schema.get("required", []))
            lines = []
            for key, value in schema["properties"].items():
                marker = "" if key in required else "?"
                lines.append(f"{_ts_string_literal(key)}{marker}: {_ts_type(value)}")
            return "{ " + "; ".join(lines) + " }"
        extra = schema.get("additionalProperties", True)
        return f"Record<string, {_ts_type(extra)}>"
    if schema_type == "string":
        return "string"
    if schema_type in ("integer", "number"):
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"
    return "unknown"


def _ts_interface(name: str, schema: dict[str, Any]) -> str:
    if "properties" in schema:
        required = set(schema.get("required", []))
        lines = [f"export interface {name} {{"]
        for key, value in schema["properties"].items():
            marker = "" if key in required else "?"
            lines.append(f"  {_ts_string_literal(key)}{marker}: {_ts_type(value)};")
        lines.append("}")
        return "\n".join(lines)
    return f"export type {name} = {_ts_type(schema)};"


def _ts_module(schemas: dict[str, Any]) -> str:
    header = (
        "// GENERATED by clinical_schemas.codegen (INT-031) from the pydantic\n"
        "// models — regenerate with `make schemas-codegen`, never edit by hand.\n"
        "// Types only: the runtime lives on the python side.\n"
    )
    blocks = [_ts_interface(name, schemas[name]) for name in sorted(schemas)]
    return header + "\n" + "\n\n".join(blocks) + "\n"


# ---------------------------------------------------------------- artefacts


def generate_artifacts() -> dict[str, str]:
    """Return every generated artefact as {path relative to the package: content}."""
    schemas = _component_schemas()
    artifacts: dict[str, str] = {
        OPENAPI_PATH: _dump_json(_openapi_document()),
        TS_PATH: _ts_module(schemas),
    }
    for schema_id, model in EVENT_MODELS.items():
        name = schema_id.removeprefix("intake.clinical.")
        event_schema = model.model_json_schema(mode="serialization")
        artifacts[f"{EVENTS_DIR}/{name}.json"] = _dump_json(event_schema)
    return artifacts


def write_artifacts(root: Path | None = None) -> list[Path]:
    """Write the artefacts under ``root`` (the package by default)."""
    base = root if root is not None else PACKAGE_ROOT
    written: list[Path] = []
    for relpath, content in sorted(generate_artifacts().items()):
        target = base / relpath
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        written.append(target)
    return written


if __name__ == "__main__":
    for path in write_artifacts():
        print(path)  # noqa: T201 — build-step CLI output
