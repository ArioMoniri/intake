"""Compiler outputs (c) and (d): Pydantic slot schemas and TypeScript types.

files/03 §6: "(c) Pydantic slot schemas for the engine, (d) TypeScript types
for the app". Both are emitted from the one resolved document, so the engine
and the app cannot drift apart, and both are keyed by the derived
``fhir_link_id`` rather than by position (files/12 §8).

Emission is deterministic by construction: sections and slots come out in
resolution order, and nothing here reads a clock, a path or an environment.
The generator style follows ``clinical_schemas.codegen`` (INT-031) so the two
committed-artefact generators in this repository read the same way.
"""

from __future__ import annotations

from typing import Final

from protocols.compile.resolve import ResolvedProtocol, ResolvedSlot
from protocols.types import SlotType

__all__ = ["model_name", "pydantic_module", "typescript_module"]

_PY_TYPE: Final[dict[SlotType, str]] = {
    SlotType.BOOLEAN: "bool",
    SlotType.INTEGER: "int",
    SlotType.DECIMAL: "Decimal",
    SlotType.STRING: "str",
    SlotType.CODE: "str",
    SlotType.DATE: "date",
    SlotType.DURATION: "timedelta",
    SlotType.QUANTITY: "Decimal",
}

# The app receives quantities as numbers and dates as ISO strings, matching
# the INT-031 TS emitter's own JSON-shaped view of the same models.
_TS_TYPE: Final[dict[SlotType, str]] = {
    SlotType.BOOLEAN: "boolean",
    SlotType.INTEGER: "number",
    SlotType.DECIMAL: "number",
    SlotType.STRING: "string",
    SlotType.CODE: "string",
    SlotType.DATE: "string",
    SlotType.DURATION: "string",
    SlotType.QUANTITY: "number",
}


def model_name(pack_id: str) -> str:
    """``base.derlenebilir`` → ``BaseDerlenebilirSlots``."""
    words = pack_id.replace(".", "_").split("_")
    return "".join(word[:1].upper() + word[1:] for word in words if word) + "Slots"


def _slots(document: ResolvedProtocol) -> list[ResolvedSlot]:
    return [slot for section in document.sections for slot in section.slots]


def _field_name(slot: ResolvedSlot) -> str:
    return f"{slot.section_id}_{slot.key}"


def pydantic_module(document: ResolvedProtocol) -> str:
    """Emit the engine-side slot schema as importable, typed source."""
    name = model_name(document.pack_id)
    lines = [
        "# GENERATED by protocols.compile (INT-041) from the resolved protocol",
        f"# {document.pack_id}@{document.version}",
        f"# resolved_protocol_hash: {document.resolved_protocol_hash}",
        "# Regenerate with `make protocols-compile`; never edit by hand.",
        "",
        "from __future__ import annotations",
        "",
        "from datetime import date, timedelta",
        "from decimal import Decimal",
        "",
        "from pydantic import BaseModel, ConfigDict, Field",
        "",
        "",
        f"class {name}(BaseModel):",
        f'    """Answer slots of {document.pack_id}. Every field is optional: an',
        "    unanswered slot is `not_asked`, which is a three-valued state and not",
        '    a false (files/12 §1.1)."""',
        "",
        '    model_config = ConfigDict(frozen=True, extra="forbid")',
        "",
    ]
    slots = _slots(document)
    if not slots:
        lines.append("    # the resolved protocol declares no slots")
    for slot in slots:
        annotation = _PY_TYPE[slot.slot.type]
        lines.append(
            f"    {_field_name(slot)}: {annotation} | None = Field("
            f'default=None, alias="{slot.fhir_link_id}")'
        )
    return "\n".join(lines) + "\n"


def typescript_module(document: ResolvedProtocol) -> str:
    """Emit the app-side type, keyed by the same linkIds as the Questionnaire."""
    name = model_name(document.pack_id)
    lines = [
        "// GENERATED by protocols.compile (INT-041) from the resolved protocol",
        f"// {document.pack_id}@{document.version}",
        f"// resolved_protocol_hash: {document.resolved_protocol_hash}",
        "// Regenerate with `make protocols-compile`; never edit by hand.",
        "// Types only: the runtime lives on the python side.",
        "",
        f"export interface {name} {{",
    ]
    for slot in _slots(document):
        lines.append(f'  "{slot.fhir_link_id}"?: {_TS_TYPE[slot.slot.type]};')
    lines.append("}")
    return "\n".join(lines) + "\n"
